"""Phase-7 strategy package (S1 contracts + S2 mechanics + S3 pairing + S4 comparison + S5 uncertainty/objectives).

S1 defined the strategy-domain intervention contract and the simulator's
default-off intervention seam. S2 executes the single-decision intervention
mechanics (STAY_OUT / PIT_NOW / PIT_NEXT_LAP) on the frozen Phase-6 simulator
and exposes the per-simulation execution outcome. S3 adds the paired
Monte-Carlo / common-random-numbers substrate (``run_pair``) that compares one
baseline against one intervention under shared simulation identities and
retains compact per-index outcomes. S4 adds the candidate generator and the
strategy comparison layer: one common baseline, each valid candidate paired
against it, transparent paired deltas and execution-status rates. S5 adds
explicit Monte Carlo SAMPLING uncertainty (paired SE, deterministic paired
bootstrap CI) and explicit objective semantics (three single-metric objectives,
direct candidate-vs-candidate pairing) as an additive view over an S4 result —
with no hidden weighted score and no simulation rerun.

Dependency direction: ``v2.strategy`` depends on ``v2.simulation``. The
simulation seam is neutral and never imports ``v2.strategy`` (see
``v2/simulation/monte_carlo.py``), so there is no package cycle.
"""

