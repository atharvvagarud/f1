"""
Build a MASTER table combining Non-Weather + Weather comparisons.

Inputs (generated by other scripts):
- results/comparisons/lap10_model_comparison.csv
- results/comparisons/lap10_weather_model_comparison.csv

Outputs:
- results/comparisons/lap10_master_comparison.csv
- results/comparisons/lap10_master_comparison.md
- results/comparisons/lap10_master_comparison_numeric.csv  (split mean/std into columns)

Run:
  python .\scripts\results\make_master_model_comparison.py
"""

from __future__ import annotations

from pathlib import Path
import re
import pandas as pd


def find_project_root(start: Path) -> Path:
    for p in [start] + list(start.parents):
        if (p / "data").exists() and (p / "scripts").exists():
            return p
    raise RuntimeError("Could not locate project root (missing data/ and scripts/).")


def markdown_table(headers: list[str], rows: list[list[str]]) -> str:
    out = []
    out.append("| " + " | ".join(headers) + " |")
    out.append("| " + " | ".join(["---"] * len(headers)) + " |")
    for r in rows:
        out.append("| " + " | ".join(r) + " |")
    return "\n".join(out) + "\n"


def parse_mean_std(text: str) -> tuple[float | None, float | None]:
    """
    Return (mean, std) from '0.5600 ± 0.1735' else (None, None) for N/A.
    """
    s = str(text).strip()
    if s.upper() == "N/A" or s == "" or s.lower() == "nan":
        return None, None
    s = s.replace("+/-", "±").replace("+-", "±").replace(" ", "")
    m = re.match(r"^([0-9]*\.?[0-9]+)±([0-9]*\.?[0-9]+)$", s)
    if not m:
        # might be a single number (no std)
        try:
            return float(s), None
        except Exception:
            return None, None
    return float(m.group(1)), float(m.group(2))


def main() -> None:
    ROOT = find_project_root(Path(__file__).resolve())
    IN_NON = ROOT / "results" / "comparisons" / "lap10_model_comparison.csv"
    IN_WTH = ROOT / "results" / "comparisons" / "lap10_weather_model_comparison.csv"

    OUT_DIR = ROOT / "results" / "comparisons"
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    OUT_CSV = OUT_DIR / "lap10_master_comparison.csv"
    OUT_MD = OUT_DIR / "lap10_master_comparison.md"
    OUT_NUM = OUT_DIR / "lap10_master_comparison_numeric.csv"

    df_non = pd.read_csv(IN_NON)
    df_non.insert(1, "dataset", "Non-Weather")

    df_wth = pd.read_csv(IN_WTH)
    df_wth.insert(1, "dataset", "Weather")

    # Standardize column names to user-friendly output
    def standardize(df: pd.DataFrame) -> pd.DataFrame:
        df = df.rename(
            columns={
                "model": "model",
                "top1_accuracy": "Top-1",
                "top3_accuracy": "Top-3",
                "log_loss": "Log Loss",
            }
        )
        return df[["model", "dataset", "Top-1", "Top-3", "Log Loss"]]

    master = pd.concat([standardize(df_non), standardize(df_wth)], ignore_index=True)

    # Remove duplicates (you had some repeated baseline rows earlier)
    master = master.drop_duplicates(subset=["model", "dataset"], keep="first").reset_index(drop=True)

    master.to_csv(OUT_CSV, index=False)

    # Markdown
    rows = master.astype(str).values.tolist()
    md = "# Lap-10 Master Comparison (Non-Weather vs Weather)\n\n"
    md += markdown_table(["Model", "Dataset", "Top-1", "Top-3", "Log Loss"], rows)
    OUT_MD.write_text(md, encoding="utf-8")

    # Numeric version
    num_rows = []
    for _, r in master.iterrows():
        t1m, t1s = parse_mean_std(r["Top-1"])
        t3m, t3s = parse_mean_std(r["Top-3"])
        llm, lls = parse_mean_std(r["Log Loss"])
        num_rows.append(
            {
                "model": r["model"],
                "dataset": r["dataset"],
                "top1_mean": t1m,
                "top1_std": t1s,
                "top3_mean": t3m,
                "top3_std": t3s,
                "logloss_mean": llm,
                "logloss_std": lls,
            }
        )
    pd.DataFrame(num_rows).to_csv(OUT_NUM, index=False)

    print(f"Saved MASTER comparison CSV: {OUT_CSV}")
    print(f"Saved MASTER comparison MD:  {OUT_MD}")
    print(f"Saved MASTER numeric CSV:    {OUT_NUM}")


if __name__ == "__main__":
    main()