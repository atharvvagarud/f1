"""V2 Strategy 2.0 HTTP schemas (V3.6F runtime integration).

Pydantic boundary for the frozen V3.6C paired-MC2 engine
(``raceintel.strategy.v3_engine``). Phase-7 ``POST /v2/strategies/compare``
is untouched: Strategy 2.0 carries a wider outcome vector
(win/podium/top5/top10/expected-finish/downside), reference/alternative
aggregates over the complete-pair set, and per-objective point-estimate
leaders, which the frozen Phase-7 schema cannot carry without ambiguous
field reinterpretation (V3.6A explicitly permits a versioned-new endpoint
in that case). Hence ``POST /v2/strategies/compare-v3``.

Frozen request policy:
- exact-anchor addressing identical to Phase-7 (no nearest/interpolation);
- ``alternatives`` is a subset of the frozen 9-action space; ``None`` runs
  the full 9-action contract set;
- production simulation count is fixed at 5000 by contract: the schema
  accepts NO simulation-count field (extra fields are forbidden);
- ``mode`` discriminates ``live`` (real engine) from ``cached``
  (artifact previously generated by the same engine).

Language policy (V3.6A/B): COMPARE / ALTERNATIVE / SIMULATED DIFFERENCE /
PAIRED SIMULATIONS / 95% MC INTERVAL. Never BEST / OPTIMAL / RECOMMENDED /
SHOULD PIT / CORRECT STRATEGY / GUARANTEED.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from raceintel.simulation.config import MAX_MASTER_SEED

V3StrategyActionValue = Literal["STAY_OUT", "PIT_NOW", "PIT_NEXT_LAP"]
V3StrategyCompoundValue = Literal["SOFT", "MEDIUM", "HARD"]
V3ExecutionModeValue = Literal["live", "cached"]


class V3AlternativeRequest(BaseModel):
    """One requested Strategy 2.0 alternative.

    ``requested_compound=None`` = sampled compound (baseline-drawn), a
    distinct frozen action from any explicit compound.
    """

    model_config = ConfigDict(extra="forbid")

    action: V3StrategyActionValue
    requested_compound: V3StrategyCompoundValue | None = None


class V3CompareRequest(BaseModel):
    """Strategy 2.0 comparison request for one exact historical state.

    The server reconstructs the factual state from the exact
    ``(race_id, anchor_driver_id, anchor_lap_number, anchor_state_time_s)``
    key. ``master_seed=None`` resolves to the deterministic production
    seed echoed in the response. ``mode="live"`` executes the validated
    engine; ``mode="cached"`` serves a deterministic artifact previously
    generated by the same engine (explicit miss when absent).
    """

    model_config = ConfigDict(extra="forbid")

    race_id: str = Field(min_length=1)
    anchor_driver_id: str = Field(min_length=1)
    anchor_lap_number: int = Field(ge=1)
    anchor_state_time_s: float = Field(allow_inf_nan=False)
    target_driver_id: str = Field(min_length=1)
    alternatives: list[V3AlternativeRequest] | None = Field(default=None)
    master_seed: int | None = Field(default=None, ge=0, le=MAX_MASTER_SEED)
    mode: V3ExecutionModeValue = "live"


class V3PositionFrequencyResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    position: int | None = None
    frequency: float


class V3ArmAggregateResponse(BaseModel):
    """Target-driver outcome aggregate over ONE complete-pair set."""

    model_config = ConfigDict(extra="forbid")

    valid_pairs: int
    win_frequency: float
    podium_frequency: float
    top5_frequency: float
    top10_frequency: float
    expected_finish: float
    median_finish: float
    finish_q25: float
    finish_q75: float
    finish_position_distribution: list[V3PositionFrequencyResponse] = []
    roster_size: int


class V3DeltaResponse(BaseModel):
    """One paired simulated difference with MC sampling uncertainty."""

    model_config = ConfigDict(extra="forbid")

    metric: str
    point_estimate: float | None = None
    paired_se: float | None = None
    ci_low: float | None = None
    ci_high: float | None = None
    availability: str
    valid_pairs: int
    uncertainty_semantics: str = ""
    interval_label: str = ""


class V3ExecutionResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    total: int
    applied: int
    suppressed: int
    superseded: int
    inert: int
    race_end_cancelled: int
    baseline_pit_suppressed: int = 0
    applied_rate: float
    suppressed_rate: float
    superseded_rate: float
    inert_rate: float
    race_end_cancelled_rate: float


class V3ComparisonKeyResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    key_version: str
    race_id: str
    decision_lap: int
    state_identity: str
    target_driver_id: str
    reference_kind: str
    alternative_identity: str
    simulator_identity: str
    parameter_identity: str
    simulation_count: int
    master_seed: int
    outcome_schema_version: str


class V3AlternativeResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    candidate_key: str
    candidate_identity: str
    action: str
    requested_compound: str | None = None
    evaluated: bool
    reason: str | None = None
    reference_aggregate: V3ArmAggregateResponse | None = None
    alternative_aggregate: V3ArmAggregateResponse | None = None
    deltas: list[V3DeltaResponse] = []
    execution: V3ExecutionResponse | None = None
    requested_pairs: int
    complete_pairs: int
    excluded_pairs: int
    comparison_key: V3ComparisonKeyResponse | None = None
    comparison_identity: str | None = None


class V3RuntimeResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    reconstruction_s: float
    adaptation_s: float = 0.0
    simulation_s: float
    analysis_s: float = 0.0
    total_s: float


class V3CompareResponse(BaseModel):
    """Strategy 2.0 comparison payload (paired simulations, compare only)."""

    model_config = ConfigDict(extra="forbid")

    engine_version: str
    execution_contract_version: str
    outcome_schema_version: str
    strategy_identity: str
    state_identity: str
    parameter_identity: str
    config_identity: str
    master_seed: int
    simulation_count: int
    race_id: str
    anchor_driver_id: str
    anchor_lap_number: int
    anchor_state_time_s: float
    target_driver_id: str
    supported: bool
    unsupported_reason: str | None = None
    reference_kind: str
    alternatives: list[V3AlternativeResponse] = []
    leaders: dict[str, str | None] = {}
    provenance: dict = {}
    execution_source: Literal["live_engine", "cache"]
    cache_key: str | None = None
    runtime: V3RuntimeResponse


class V3AvailabilityEntry(BaseModel):
    model_config = ConfigDict(extra="forbid")

    race_id: str
    anchor_driver_id: str
    anchor_lap_number: int
    anchor_state_time_s: float
    target_driver_id: str
    master_seed: int
    simulation_count: int
    supported: bool
    alternative_count: int
    comparison_identities: list[str] = []
    cache_key: str


class V3AvailabilityResponse(BaseModel):
    model_config = ConfigDict(extra="forbid")

    engine_version: str
    execution_contract_version: str
    outcome_schema_version: str
    manifest_schema: str
    entry_count: int
    entries: list[V3AvailabilityEntry] = []


class V3StrategyErrorResponse(BaseModel):
    error: str
    detail: str = ""
    reason: str | None = None
