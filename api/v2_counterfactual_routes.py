"""V2 counterfactual HTTP routes (V3.7F runtime integration).

Additive counterfactual family over ``CounterfactualService``. Thin
routing only: request parsing via ``api.v2_counterfactual_schemas``,
orchestration via ``api.v2_counterfactual_service``, domain-error to
HTTP mapping below. Phase-7 and V3.6 routes, services and schemas are
untouched and unimported here.

Error mapping (frozen conventions followed):
- unknown race (2018-2024 registry miss, incl. any 2025 race) -> 404
  ``unknown_race``
- exact-anchor miss / malformed anchor / invalid reconstructed state ->
  422 ``unknown_state``
- malformed counterfactual request (unknown kind/compound/form,
  conflicting targets, forbidden extra fields such as simulation counts,
  seeds, historical-future smuggling, or live-mode overrides) -> 422
  ``counterfactual_request_invalid`` with the stable machine-readable
  ``reason`` (pydantic schema violations use FastAPI's default 422
  body for the same status)
- a well-formed but un-simulatable factual state or plan -> 200 with
  ``supported=false`` and the canonical eligibility ``reason_code``. No
  fallback, no fabricated results, no zero-filled metrics.
- valid but cache-missing with live disabled -> 404 ``cache_miss``
  (explicit; never a silent fallback to fabricated numbers)
- corrupt/stale/mismatched cache artifact with live disabled -> 503
  ``cache_invalid``
- frozen parameter artifact missing/corrupt -> 503
  ``parameter_unavailable``
- anything else -> 500 ``internal`` (never disguised as a client error)

Error bodies never carry stack traces, filesystem paths, or model internals.
"""

from __future__ import annotations

from fastapi import APIRouter, Depends, Query
from fastapi.responses import JSONResponse

from api import v2_counterfactual_schemas as S
from api.v2_counterfactual_service import (
    CounterfactualService,
    get_counterfactual_service,
)
from api.v2_strategy_service import StrategyParameterUnavailableError
from raceintel.counterfactual.runtime import (
    CacheInvalidError,
    CacheMissError,
    RuntimeRequestError,
)
from raceintel.race_state.race_state import InvalidRaceStateError
from raceintel.race_state.race_state_reconstruction import (
    AnchorNotFoundError,
    RaceNotFoundError,
    RaceStateReconstructionError,
)
from raceintel.simulation.adapter import SimulationUnavailableError
from raceintel.simulation.engine import SimulationUnsupportedError

router = APIRouter(prefix="/v2", tags=["v2-counterfactuals"])


def _unknown_race(race_id: str) -> dict:
    return {"error": "unknown_race",
            "detail": f"no served race {race_id!r}"}


def _unknown_state(race_id: str) -> dict:
    return {"error": "unknown_state",
            "detail": f"no exact anchor state for {race_id!r}; "
                      f"list exact anchors via /v2/races/{race_id}/states"}


def _invalid(exc: RuntimeRequestError) -> dict:
    return {"error": "counterfactual_request_invalid",
            "reason": exc.reason, "detail": exc.detail}


def _unavailable() -> dict:
    return {"error": "parameter_unavailable",
            "detail": "frozen production parameters unavailable"}


def _internal() -> dict:
    return {"error": "internal",
            "detail": "unexpected counterfactual failure"}


@router.post("/counterfactuals/compare",
             response_model=S.CounterfactualCompareResponse)
def compare_counterfactuals(
        payload: S.CounterfactualCompareRequest,
        service: CounterfactualService = Depends(
            get_counterfactual_service)):
    """Counterfactual comparison for one exact historical state.

    Cache-first: serves a validated deterministic artifact previously
    generated by the frozen V3.7C engine at the production 5000-future
    configuration. Live 5000-future execution happens only on cache miss
    when the server explicitly enables it; otherwise the miss is an
    explicit 404. Compare only: paired simulations, simulated
    differences, paired uncertainty. Never a recommendation.
    """
    try:
        return service.run_comparison(
            race_id=payload.race_id,
            anchor_driver_id=payload.anchor_driver_id,
            anchor_lap_number=payload.anchor_lap_number,
            anchor_state_time_s=payload.anchor_state_time_s,
            comparison_form=payload.comparison_form,
            base_plan=(payload.base_plan.model_dump()
                       if payload.base_plan is not None else None),
            alternative_plan=payload.alternative_plan.model_dump(),
            rival_driver_id=payload.rival_driver_id)
    except RaceNotFoundError:
        return JSONResponse(status_code=404,
                            content=_unknown_race(payload.race_id))
    except (AnchorNotFoundError, InvalidRaceStateError,
            RaceStateReconstructionError):
        return JSONResponse(status_code=422,
                            content=_unknown_state(payload.race_id))
    except RuntimeRequestError as exc:
        return JSONResponse(status_code=422, content=_invalid(exc))
    except CacheMissError as exc:
        return JSONResponse(
            status_code=404,
            content={"error": "cache_miss", "detail": str(exc)})
    except CacheInvalidError as exc:
        return JSONResponse(
            status_code=503,
            content={"error": "cache_invalid", "detail": str(exc)})
    except (SimulationUnsupportedError, SimulationUnavailableError):
        return JSONResponse(status_code=500, content=_internal())
    except StrategyParameterUnavailableError:
        return JSONResponse(status_code=503, content=_unavailable())
    except Exception:  # noqa: BLE001 - stable 500, never a client error
        return JSONResponse(status_code=500, content=_internal())


@router.get("/counterfactuals/availability",
            response_model=S.CounterfactualAvailabilityResponse)
def counterfactual_availability(
        race_id: str = Query(min_length=1),
        anchor_driver_id: str = Query(min_length=1),
        anchor_lap_number: int = Query(ge=1),
        anchor_state_time_s: float = Query(allow_inf_nan=False),
        service: CounterfactualService = Depends(
            get_counterfactual_service)):
    """Cheap factual availability for one exact historical state.

    Resolves the factual RaceState(T) only: no simulation, no futures.
    Reports the state identity, per-driver decision laps and eligible
    N ranges, supported compounds, rival candidates, multi-stop and
    multi-driver capability, cached comparison identities, and frozen
    provenance. Never exposes historical future, future strategy, or
    results.
    """
    try:
        return service.describe_availability(
            race_id=race_id, anchor_driver_id=anchor_driver_id,
            anchor_lap_number=anchor_lap_number,
            anchor_state_time_s=anchor_state_time_s)
    except RaceNotFoundError:
        return JSONResponse(status_code=404,
                            content=_unknown_race(race_id))
    except (AnchorNotFoundError, InvalidRaceStateError,
            RaceStateReconstructionError):
        return JSONResponse(status_code=422,
                            content=_unknown_state(race_id))
    except StrategyParameterUnavailableError:
        return JSONResponse(status_code=503, content=_unavailable())
    except Exception:  # noqa: BLE001 - stable 500, never a client error
        return JSONResponse(status_code=500, content=_internal())
