#: Deterministic default seed (the R7 validation seed, shared with Phase-7).
#: Requests may override it; the resolved seed is echoed and is part of the
#: cache key.
DEFAULT_MASTER_SEED = 20240101

#: Production parameter artifact is the frozen R3 through-2024 estimation.
PRODUCTION_PARAMETER_SEASON = 2024

#: Cache identity/schema versions (runtime-owned; scientific identities are
#: imported from the frozen contracts above and invalidate naturally).
CACHE_KEY_VERSION = "v3.6f-strategy-cache-key-v1"
CACHE_SCHEMA_VERSION = "v3.6f-strategy-cache-v1"
MANIFEST_SCHEMA_VERSION = "v3.6f-strategy-manifest-v1"

