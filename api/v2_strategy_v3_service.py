#: Frozen 9-action space as (action, requested_compound) string pairs.
FROZEN_ACTION_SET = tuple(
    (spec[0].value if hasattr(spec[0], "value") else str(spec[0]), spec[1])
    for spec in CANONICAL_CANDIDATE_SPECS
)

#: Comparison-level zero-pair reason (mirrors the frozen engine constant).
NO_VALID_PAIRS = "NO_VALID_PAIRS"

#: Machine wording for the served interval label (frozen engine wording).
MC_INTERVAL_LABEL = "95% MC interval"


class V3RequestError(ValueError):
    """A product-level request validation failure (maps to 422)."""

    def __init__(self, reason: str, detail: str = ""):
        super().__init__(detail or reason)
        self.reason = reason
        self.detail = detail or reason


class V3CacheMissError(RuntimeError):
    """No cache artifact exists for the requested comparison identity."""


class V3CacheInvalidError(RuntimeError):
    """A cache artifact failed validation (never served)."""


class V3LiveDisabledError(RuntimeError):
    """Live engine execution is disabled in this runtime (cache-only)."""


def resolve_alternative_specs(
        alternatives: list | tuple | None) -> list[tuple[str, str | None]]:
    """Normalize the request alternative list to ``(action, compound)``."""
    if alternatives is None:
        return list(FROZEN_ACTION_SET)
    specs = []
    for entry in alternatives:
        if isinstance(entry, dict):
            specs.append((entry["action"], entry.get("requested_compound")))
        else:
            specs.append((getattr(entry, "action"),
                          getattr(entry, "requested_compound")))
    return specs


def validate_alternative_specs(specs: list) -> None:
    """Fail closed on non-conforming Strategy 2.0 alternative sets."""
    if not specs:
        raise V3RequestError(
            "no_alternatives", "select at least one strategy alternative")
    if len(specs) > len(FROZEN_ACTION_SET):
        raise V3RequestError(
            "too_many_alternatives",
            f"at most {len(FROZEN_ACTION_SET)} alternatives per comparison")
    frozen = set(FROZEN_ACTION_SET)
    for action, compound in specs:
        if (action, compound) not in frozen:
            raise V3RequestError(
                "invalid_action",
                f"alternative {(action, compound)!r} is outside the frozen "
                f"9-action Strategy 2.0 space")
    keys = [f"{action}:{compound or 'SAMPLED'}" for action, compound in specs]
    if len(set(keys)) != len(keys):
        raise V3RequestError(
            "duplicate_alternatives",
            "alternative selection contains duplicates; "
            "each (action, compound) may appear once")


def build_cache_key(*, state_identity: str, parameter_identity: str,
                     config_identity: str, simulation_count: int,
                     master_seed: int, target_driver_id: str) -> str:
    """Deterministic cache identity from frozen scientific identities.

    Built only from scientific identity (engine/contract/outcome/MC2
    versions plus state/parameter/config/target/seed/count). No
    timestamps, no filesystem paths, no presentation state: any
    scientific change invalidates naturally.
    """
    return canonical_sha256({
        "key_version": CACHE_KEY_VERSION,
        "engine_version": V3_ENGINE_VERSION,
        "execution_contract_version": V3B_EXECUTION_CONTRACT_VERSION,
        "outcome_schema_version": OUTCOME_SCHEMA_VERSION,
        "mc2_identity": SIMULATOR_IDENTITY,
        "state_identity": state_identity,
        "parameter_identity": parameter_identity,
        "config_identity": config_identity,
        "simulation_count": simulation_count,
        "master_seed": master_seed,
        "target_driver_id": target_driver_id,
    })


def cache_filename(cache_key: str) -> str:
    """Hex-only artifact filename (path traversal impossible)."""
    if (len(cache_key) != 64
            or any(c not in "0123456789abcdef" for c in cache_key)):
        raise V3CacheInvalidError(f"non-canonical cache key {cache_key!r}")
    return f"v3strat_{cache_key}.json"


def served_strategy_identity(scientific: dict) -> str:
    """Recompute the frozen result identity over served scientific content.

    Uses exactly the field set of ``V3StrategyResult.identity()``;
    presentation-only fields (runtime, execution source) never enter.
    """
    return canonical_sha256({
        "engine_version": scientific["engine_version"],
        "execution_contract_version":
            scientific["execution_contract_version"],
        "outcome_schema_version": scientific["outcome_schema_version"],
        "state_identity": scientific["state_identity"],
        "parameter_identity": scientific["parameter_identity"],
        "config_identity": scientific["config_identity"],
        "master_seed": scientific["master_seed"],
        "simulation_count": scientific["simulation_count"],
        "target_driver_id": scientific["target_driver_id"],
        "supported": scientific["supported"],
        "unsupported_reason": scientific["unsupported_reason"],
        "alternatives": scientific["alternatives"],
        "leaders": scientific["leaders"],
    })


def _recompute_leaders(alternatives: list) -> dict:
    """Frozen engine leader rule over a served alternative subset.

    Max point estimate wins in every leader field (all deltas use the
    positive-improvement orientation); field set imported from the
    frozen engine, never redefined here.
    """
    leaders = {}
    evaluated = [a for a in alternatives if a.get("evaluated")]
    for fname in _LEADER_FIELDS:
        best = None
        for alt in evaluated:
            point = next(d["point_estimate"] for d in alt["deltas"]
                         if d["metric"] == fname)
            if best is None or (point is not None and (
                    best[1] is None or point > best[1])):
                best = (alt["candidate_key"], point)
        leaders["leader_for_" + fname.replace("delta_", "")] = (
            best[0] if best is not None else None)
    return leaders


def slice_cached_result(stored: dict,
                        specs: list[tuple[str, str | None]]) -> dict:
    """Serve a requested alternative subset from a full cached result.

    Reproduces a live subset run exactly: requested-order alternatives,
    leaders recomputed with the frozen rule, identity recomputed over
    served content.
    """
    wanted = {f"{a}:{c or 'SAMPLED'}" for a, c in specs}
    # Preserve the cached canonical engine order (never request order):
    # the engine emits alternatives in canonical order, and order
    # determines tie-breaking in leaders plus identity hashing, so a
    # served subset must match a live subset run for the same SET
    # regardless of request order.
    served_alts = [a for a in stored["alternatives"]
                   if a["candidate_key"] in wanted]
    if len(served_alts) != len(wanted):
        raise V3CacheInvalidError(
            "cached artifact lacks a requested alternative")
    if not stored.get("supported"):
        served = dict(stored)
        served["alternatives"] = served_alts
    else:
        evaluated = [a for a in served_alts if a.get("evaluated")]
        served = dict(stored)
        served["alternatives"] = served_alts
        served["leaders"] = _recompute_leaders(served_alts)
        served["supported"] = bool(evaluated)
        served["unsupported_reason"] = (
            None if evaluated else NO_VALID_PAIRS)
        # Mirror a live subset run exactly: provenance aggregates cover
        # the served subset only (all other provenance fields are
        # subset-invariant engine output carried verbatim).
        provenance = dict(served.get("provenance") or {})
        provenance["action_identity"] = [
            a["candidate_identity"] for a in evaluated]
        provenance["complete_pair_count"] = sum(
            a["complete_pairs"] for a in evaluated)
        served["provenance"] = provenance
    served["strategy_identity"] = served_strategy_identity(served)
    return served


def validate_cached_artifact(artifact: dict, *, cache_key: str,
                             state_identity: str, parameter_identity: str,
                             config_identity: str, simulation_count: int,
                             master_seed: int,
                             target_driver_id: str) -> dict:
    """Fail-closed validation of one cache artifact (never serve stale)."""
    if not isinstance(artifact, dict):
        raise V3CacheInvalidError("artifact must be a JSON object")
    if artifact.get("cache_schema_version") != CACHE_SCHEMA_VERSION:
        raise V3CacheInvalidError(
            "schema mismatch: "
            f"{artifact.get('cache_schema_version')!r}")
    if artifact.get("cache_key") != cache_key:
        raise V3CacheInvalidError("cache key mismatch")
    stored = artifact.get("result")
    if not isinstance(stored, dict):
        raise V3CacheInvalidError("artifact lacks result payload")
    for field, expected in (
            ("engine_version", V3_ENGINE_VERSION),
            ("execution_contract_version", V3B_EXECUTION_CONTRACT_VERSION),
            ("outcome_schema_version", OUTCOME_SCHEMA_VERSION),
            ("state_identity", state_identity),
            ("parameter_identity", parameter_identity),
            ("config_identity", config_identity),
            ("simulation_count", simulation_count),
            ("master_seed", master_seed),
            ("target_driver_id", target_driver_id)):
        if stored.get(field) != expected:
            raise V3CacheInvalidError(
                f"provenance mismatch on {field}")
    provenance = stored.get("provenance") or {}
    if provenance.get("mc2_identity") != SIMULATOR_IDENTITY:
        raise V3CacheInvalidError("MC2 identity mismatch")
    if stored.get("strategy_identity") != served_strategy_identity(stored):
        raise V3CacheInvalidError("result identity mismatch (corrupt)")
    return stored


def build_cache_artifact(*, cache_key: str, result_dict: dict,
                         request_meta: dict) -> dict:
    """Wrap a validated engine result dict as a deterministic artifact."""
    recomputed = served_strategy_identity(result_dict)
    if result_dict.get("strategy_identity") != recomputed:
        raise ValueError("engine result identity mismatch (refusing cache)")
    return {
        "cache_schema_version": CACHE_SCHEMA_VERSION,
        "cache_key_version": CACHE_KEY_VERSION,
        "cache_key": cache_key,
        "result": result_dict,
        "request": request_meta,
    }


def artifact_bytes(artifact: dict) -> bytes:
    """Canonical artifact serialization (stable field order)."""
    return json.dumps(artifact, sort_keys=True, indent=2).encode("utf-8")


def artifact_hash(artifact: dict) -> str:
    return hashlib.sha256(artifact_bytes(artifact)).hexdigest()


def write_cache_artifact(cache_dir: Path, artifact: dict) -> Path:
    """Atomic, resume-safe artifact write (validated before write)."""
    path = Path(cache_dir) / cache_filename(artifact["cache_key"])
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_bytes(artifact_bytes(artifact))
    os.replace(tmp, path)
    return path


def read_cache_artifact(cache_dir: Path, cache_key: str) -> dict:
    """Load one artifact by key (hex-only filename; miss is explicit)."""
    path = Path(cache_dir) / cache_filename(cache_key)
    try:
        raw = path.read_bytes()
    except FileNotFoundError as exc:
        raise V3CacheMissError(
            f"no cached Strategy 2.0 result for {cache_key[:12]}…") from exc
    try:
        artifact = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as exc:
        raise V3CacheInvalidError(
            f"malformed cache artifact {path.name}") from exc
    return artifact


def build_manifest(entries: list, *, status: str = "fixture") -> dict:
    """Deterministic cache manifest (ordering fixed, no local paths)."""
    ordered = sorted(
        entries,
        key=lambda e: (e.get("race_id", ""), e.get("anchor_lap_number", 0),
                       str(e.get("anchor_state_time_s", 0.0)),
                       e.get("target_driver_id", "")))
    return {
        "manifest_schema": MANIFEST_SCHEMA_VERSION,
        "status": status,
        "engine_version": V3_ENGINE_VERSION,
        "execution_contract_version": V3B_EXECUTION_CONTRACT_VERSION,
        "outcome_schema_version": OUTCOME_SCHEMA_VERSION,
        "comparison_key_version": COMPARISON_KEY_VERSION,
        "mc2_identity": SIMULATOR_IDENTITY,
        "reference_kind": REFERENCE_KIND,
        "simulation_count": PRODUCTION_SIMULATION_COUNT,
        "trade_off_fields": list(TRADE_OFF_FIELDS),
        "entry_count": len(ordered),
        "entries": ordered,
    }


class V3StrategyService:
    """Reusable Strategy 2.0 product runtime (live engine + honest cache)."""

    def __init__(self, states: pd.DataFrame, reconstructor,
                 served_race_ids, parameters: SimulationParameterSet, *,
                 cache_dir: Path | str | None = None,
                 allow_live: bool = True,
                 simulation_count: int = PRODUCTION_SIMULATION_COUNT,
                 chunk_size: int | None = None):
        if not isinstance(states, pd.DataFrame):
            raise ValueError(f"states must be a DataFrame, got {type(states)}")
        if not isinstance(parameters, SimulationParameterSet):
            raise TypeError(
                "parameters must be a SimulationParameterSet, "
                f"got {type(parameters)}")
        self._states = states
        self._reconstructor = reconstructor
        self._served = tuple(served_race_ids)
        self._parameters = parameters
        self._cache_dir = Path(cache_dir) if cache_dir is not None \
            else Path(os.environ.get("V3_STRATEGY_CACHE_DIR",
                                     str(DEFAULT_CACHE_DIR)))
        self._allow_live = bool(allow_live) and os.environ.get(
            "V3_STRATEGY_ALLOW_LIVE", "1") != "0"
        self._simulation_count = int(simulation_count)
        self._chunk_size = chunk_size

    @property
    def race_ids(self) -> tuple:
        return self._served

    @property
    def simulation_count(self) -> int:
        return self._simulation_count

    @property
    def cache_dir(self) -> Path:
        return self._cache_dir

    @property
    def allow_live(self) -> bool:
        return self._allow_live

    def _require_race(self, race_id: str) -> None:
        if race_id not in self._served:
            raise RaceNotFoundError(race_id)

    def _reconstruct(self, *, race_id: str, anchor_driver_id: str,
                     anchor_lap_number: int,
                     anchor_state_time_s: float):
        self._require_race(race_id)
        anchor = RS.AnchorObservation(
            race_id=race_id, anchor_driver_id=anchor_driver_id,
            anchor_lap_number=anchor_lap_number,
            anchor_state_time_s=anchor_state_time_s)
        return self._reconstructor.reconstruct(anchor)

    def _request_identities(self, *, sim_state, master_seed: int,
                            target_driver_id: str):
        config = SimulationConfig(
            simulation_count=self._simulation_count,
            master_seed=master_seed, pit_dynamics_enabled=True)
        return config, {
            "state_identity": sim_state.identity(),
            "parameter_identity":
                self._parameters.parameter_identity().identity(),
            "config_identity": config.identity(),
        }

    def run_comparison(
            self, *, race_id: str, anchor_driver_id: str,
            anchor_lap_number: int, anchor_state_time_s: float,
            target_driver_id: str,
            alternatives: list | tuple | None = None,
            master_seed: int | None = None,
            mode: str = "live") -> dict:
        """Run (live) or serve (cached) one Strategy 2.0 comparison."""
        if mode not in ("live", "cached"):
            raise V3RequestError(
                "unknown_mode",
                f"mode must be 'live' or 'cached', got {mode!r}")
        if (master_seed is not None
                and not 0 <= master_seed <= MAX_MASTER_SEED):
            # Bound enforced by schema; defense in depth.
            raise V3RequestError(
                "seed_out_of_bounds", "master_seed out of bounds")
        specs = resolve_alternative_specs(alternatives)
        validate_alternative_specs(specs)
        seed = DEFAULT_MASTER_SEED if master_seed is None else int(master_seed)

        total_started = time.perf_counter()
        race_state = self._reconstruct(
            race_id=race_id, anchor_driver_id=anchor_driver_id,
            anchor_lap_number=anchor_lap_number,
            anchor_state_time_s=anchor_state_time_s)
        reconstructed = time.perf_counter()
        # Adaptation is cheap (no simulation) and the adapted
        # SimulationState is the frozen identity authority used by the
        # engine itself (S4 state_identity), so both modes share it.
        sim_state = from_race_state(race_state)
        adapted = time.perf_counter()
        config, ids = self._request_identities(
            sim_state=sim_state, master_seed=seed,
            target_driver_id=target_driver_id)
        cache_key = build_cache_key(
            state_identity=ids["state_identity"],
            parameter_identity=ids["parameter_identity"],
            config_identity=ids["config_identity"],
            simulation_count=self._simulation_count,
            master_seed=seed, target_driver_id=target_driver_id)

        if mode == "cached":
            artifact = read_cache_artifact(self._cache_dir, cache_key)
            stored = validate_cached_artifact(
                artifact, cache_key=cache_key,
                state_identity=ids["state_identity"],
                parameter_identity=ids["parameter_identity"],
                config_identity=ids["config_identity"],
                simulation_count=self._simulation_count,
                master_seed=seed, target_driver_id=target_driver_id)
            scientific = slice_cached_result(stored, specs)
            simulated = time.perf_counter()
            return _response_payload(
                race_id=race_id, anchor_driver_id=anchor_driver_id,
                anchor_lap_number=anchor_lap_number,
                anchor_state_time_s=anchor_state_time_s,
                target_driver_id=target_driver_id,
                scientific=scientific, execution_source="cache",
                cache_key=cache_key,
                runtime={
                    "reconstruction_s": reconstructed - total_started,
                    "adaptation_s": adapted - reconstructed,
                    "simulation_s": simulated - adapted,
                    "analysis_s": 0.0,
                    "total_s": simulated - total_started,
                })

        if not self._allow_live:
            raise V3LiveDisabledError(
                "live Strategy 2.0 execution is disabled in this "
                "runtime; use mode='cached'")
        kwargs: dict = {
            "execution_policy": ExecutionPolicy.RETROSPECTIVE_PRODUCT,
        }
        if self._chunk_size is not None:
            kwargs["chunk_size"] = self._chunk_size
        result = compare_v3_strategies(
            sim_state, self._parameters, config, Assumptions(),
            target_driver_id, candidate_specs=specs, **kwargs)
        simulated = time.perf_counter()
        scientific = result.to_dict()
        # NOTE: live runs use the requested spec order directly from the
        # engine (no slicing needed); identity comes from the engine dict.
        analyzed = time.perf_counter()
        return _response_payload(
            race_id=race_id, anchor_driver_id=anchor_driver_id,
            anchor_lap_number=anchor_lap_number,
            anchor_state_time_s=anchor_state_time_s,
            target_driver_id=target_driver_id,
            scientific=scientific, execution_source="live_engine",
            cache_key=cache_key,
            runtime={
                "reconstruction_s": reconstructed - total_started,
                "adaptation_s": adapted - reconstructed,
                "simulation_s": simulated - adapted,
                "analysis_s": analyzed - simulated,
                "total_s": analyzed - total_started,
            })

    def describe_availability(self) -> dict:
        """Deterministic catalogue of validated cached comparisons."""
        entries = []
        cache_dir = Path(self._cache_dir)
        if cache_dir.is_dir():
            for path in sorted(cache_dir.glob("v3strat_*.json")):
                try:
                    artifact = json.loads(path.read_bytes().decode("utf-8"))
                    stored = artifact.get("result") or {}
                    meta = artifact.get("request") or {}
                    entries.append({
                        "race_id": meta.get("race_id", ""),
                        "anchor_driver_id": meta.get(
                            "anchor_driver_id", ""),
                        "anchor_lap_number": meta.get(
                            "anchor_lap_number", 0),
                        "anchor_state_time_s": meta.get(
                            "anchor_state_time_s", 0.0),
                        "target_driver_id": stored.get(
                            "target_driver_id", ""),
                        "master_seed": stored.get("master_seed", 0),
                        "simulation_count": stored.get(
                            "simulation_count", 0),
                        "supported": bool(stored.get("supported")),
                        "alternative_count": len(
                            stored.get("alternatives", [])),
                        "comparison_identities": sorted(
                            a.get("comparison_identity")
                            for a in stored.get("alternatives", [])
                            if a.get("comparison_identity")),
                        "cache_key": artifact.get("cache_key", ""),
                    })
                except (ValueError, UnicodeDecodeError, OSError):
                    continue
        return {
            "engine_version": V3_ENGINE_VERSION,
            "execution_contract_version": V3B_EXECUTION_CONTRACT_VERSION,
            "outcome_schema_version": OUTCOME_SCHEMA_VERSION,
            "manifest_schema": MANIFEST_SCHEMA_VERSION,
            "entry_count": len(entries),
            "entries": sorted(
                entries,
                key=lambda e: (e["race_id"], e["anchor_lap_number"],
                               str(e["anchor_state_time_s"]),
                               e["target_driver_id"])),
        }


def _response_payload(*, race_id: str, anchor_driver_id: str,
                      anchor_lap_number: int, anchor_state_time_s: float,
                      target_driver_id: str, scientific: dict,
                      execution_source: str, cache_key: str,
                      runtime: dict) -> dict:
    return {
        "engine_version": scientific["engine_version"],
        "execution_contract_version":
            scientific["execution_contract_version"],
        "outcome_schema_version": scientific["outcome_schema_version"],
        "strategy_identity": scientific["strategy_identity"],
        "state_identity": scientific["state_identity"],
        "parameter_identity": scientific["parameter_identity"],
        "config_identity": scientific["config_identity"],
        "master_seed": scientific["master_seed"],
        "simulation_count": scientific["simulation_count"],
        "race_id": race_id,
        "anchor_driver_id": anchor_driver_id,
        "anchor_lap_number": anchor_lap_number,
        "anchor_state_time_s": anchor_state_time_s,
        "target_driver_id": target_driver_id,
        "supported": scientific["supported"],
        "unsupported_reason": scientific["unsupported_reason"],
        "reference_kind": scientific.get("reference_kind", REFERENCE_KIND),
        "alternatives": scientific["alternatives"],
        "leaders": scientific["leaders"],
        "provenance": scientific["provenance"],
        "execution_source": execution_source,
        "cache_key": cache_key,
        "runtime": runtime,
    }


def load_production_parameters(
        project_root=None) -> SimulationParameterSet:
    """Load the frozen through-2024 R3 artifact once (read-only)."""
    from api.v2_strategy_service import (
        StrategyParameterUnavailableError,
        load_production_parameters as _load,
    )
    try:
        return _load(project_root)
    except StrategyParameterUnavailableError as exc:
        from api.v2_strategy_service import (
            StrategyParameterUnavailableError as _E)
        raise _E(str(exc)) from exc


def build_v3_strategy_service(
        v2_service, *, parameters: SimulationParameterSet | None = None,
        cache_dir: Path | str | None = None,
        allow_live: bool = True,
        simulation_count: int = PRODUCTION_SIMULATION_COUNT,
        chunk_size: int | None = None):
    """Share the loaded corpus/reconstructor read-only; build no model."""
    from api.v2_service import V2Service as _V2Service
    if not isinstance(v2_service, _V2Service):
        raise ValueError(
            f"v2_service must be a V2Service, got {type(v2_service)}")
    if parameters is None:
        parameters = load_production_parameters()
    return V3StrategyService(
        v2_service._states,  # noqa: SLF001 - shared read-only corpus
        v2_service._reconstructor,  # noqa: SLF001 - shared read-only index
        v2_service.race_ids, parameters, cache_dir=cache_dir,
        allow_live=allow_live, simulation_count=simulation_count,
        chunk_size=chunk_size)


@functools.lru_cache(maxsize=1)
def _cached_v3_strategy_service() -> V3StrategyService:
    from api.v2_service import get_v2_service
    return build_v3_strategy_service(get_v2_service())


def get_v3_strategy_service() -> V3StrategyService:
    """FastAPI dependency: process-local lazy singleton (override in tests)."""
    return _cached_v3_strategy_service()
