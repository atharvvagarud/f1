"""V2 Strategy 2.0 runtime service (V3.6F integration).

Narrow product orchestration over the frozen V3.6C paired-MC2 engine
(``raceintel.strategy.v3_engine``), reusing the frozen Phase-4 exact-anchor
authority, the frozen through-2024 parameters, and the S7 adaption path:

    exact anchor -> RaceState (Phase-4) -> SimulationState (R2 adapter)
    -> frozen through-2024 parameters -> V3.6C compare_v3_strategies
    -> compact API projection   (LIVE_ENGINE)
    -> deterministic cache artifact (CACHED)

Design rules (V3.6F):
- No Strategy science lives here: no candidate semantics, no CRN policy, no
  delta estimand, no bootstrap, no leader rule, no simulation dynamics. The
  leader rule and identity rule are imported from the frozen engine
  modules, never redefined.
- Production simulation count is fixed at
  ``PRODUCTION_SIMULATION_COUNT`` (5000) by contract. The request schema
  carries no count field; the count is a construction-time constant of
  this service (tests may construct small-count services; production
  routes always use the default).
- LIVE_ENGINE calls the validated V3.6C engine on every request.
- CACHED returns an artifact previously generated by the same engine and
  validates it on every read (schema, key, identities, provenance).
  Corrupt/stale/mismatched artifacts are never served.
- Cache artifacts cover the FULL frozen 9-action set per
  (state, target, seed); subset requests are served by slicing cached
  alternatives and recomputing leaders with the frozen engine rule, which
  reproduces a live subset run exactly (parity-tested).
- Per-index outcomes never leave this process: cache and API carry
  aggregates, paired deltas and execution diagnostics only.
"""

